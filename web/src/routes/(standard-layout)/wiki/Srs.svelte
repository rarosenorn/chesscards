<h3>Chapter progression</h3>

<p>
	A deck can hold its later chapters shut until the earlier ones are
	learned, so a long deck introduces itself in order instead of all at once.
	Turn it on under the deck's <strong>Settings</strong>.
</p>

<p>
	A chapter <strong>passes</strong> when both are true of its cards:
</p>
<ul>
	<li>every card has been <strong>seen</strong> — met at least once</li>
	<li>at least <strong>80%</strong> have <strong>graduated</strong> — proved
		once, meaning they have reached Review. A card that lapses back to
		Relearning still counts: it was proved, and a lapse does not un-prove
		it. A tactic card graduates when you get it right and it finishes.</li>
</ul>

<p>
	Chapters open <strong>cumulatively</strong>: the first is always open, and
	each next one opens once every chapter before it has passed. So a chapter
	is locked while any earlier one is still short of the bar, and study says
	which one is holding it and how far along that one is.
</p>

<p>
	Progression gates only the <strong>introduction of unseen cards</strong>.
	A card you have already met keeps coming back for review on schedule even
	if its chapter has since fallen behind the bar — because cards were moved,
	or chapters regrouped. Locking a chapter never takes work away from you;
	it only stops new work arriving.
</p>

<p>
	Nothing is stored as an unlock flag. Whether a chapter is open is worked
	out from the cards themselves each time, so resetting a deck's schedule
	re-locks its later chapters by itself, and moving cards between chapters
	takes effect immediately.
</p>

<p>
	An empty chapter passes with nothing to prove, so it never holds up the
	ones after it.
</p>

<p>
	<em>Claude:</em> boards carry arrows and circles drawn with the right
	mouse button — drag between two squares for an arrow, click one square for
	a circle. Right-clicking the same thing again removes it. Four colours are
	available, chosen by holding a modifier while you draw:
</p>

<table>
	<thead>
		<tr><th>Hold</th><th>Colour</th></tr>
	</thead>
	<tbody>
		<tr><td>nothing</td><td>Green</td></tr>
		<tr><td>Alt</td><td>Blue</td></tr>
		<tr><td>Shift <em>or</em> Ctrl</td><td>Red</td></tr>
		<tr><td>Shift + Alt</td><td>Orange</td></tr>
	</tbody>
</table>

<p>
	<em>Claude:</em> the app enforces no meaning — an arrow is stored with its
	colour and drawn back as you left it. The meanings below are the
	convention from
	<a href="https://lichess.org/study/C5GpgbT8" rel="noreferrer">General
	Guidelines on Drawing Arrows</a>, a Lichess study by CreativeBro (marked
	there as a draft). The modifier keys are the same ones this editor uses.
</p>

<h3>Green — what is good now</h3>
<ul>
	<li><strong>Arrows:</strong> good moves, or good possible moves, in the current position.</li>
	<li><strong>Circles:</strong> a good or important piece; an outpost.</li>
</ul>

<h3>Blue — ideas and plans</h3>
<ul>
	<li><strong>Arrows:</strong> ideas that may not be good <em>now</em> but
		are the plan later; general themes and structural features.</li>
	<li><strong>Circles:</strong> squares that matter, potentially.</li>
</ul>

<h3>Red — the opponent</h3>
<ul>
	<li><strong>Arrows:</strong> the opponent's threats.</li>
	<li><strong>Circles:</strong> weak squares, and squares under threat.</li>
</ul>

<h3>Orange — variations</h3>
<ul>
	<li><strong>Arrows:</strong> the moves available here, so the alternatives
		can be read off the board at once.</li>
	<li><strong>Circles:</strong> the main variation among them.</li>
</ul>

<p>
	<em>Claude:</em> whatever you settle on, keep it the same across a deck. A
	colour that means one thing on one card and something else on the next
	costs more attention than it saves.
</p>


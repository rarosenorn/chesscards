<p>
	<em>Claude:</em> boards carry arrows and circles drawn with the right
	mouse button — drag between two squares for an arrow, click one square for
	a circle. Right-clicking the same thing again removes it.
</p>

<p>
	Four colours are available, chosen by holding a modifier while you draw:
</p>

<table>
	<thead>
		<tr><th>Hold</th><th>Colour</th></tr>
	</thead>
	<tbody>
		<tr><td>nothing</td><td>Green</td></tr>
		<tr><td>Alt</td><td>Blue</td></tr>
		<tr><td>Shift <em>or</em> Ctrl</td><td>Red</td></tr>
		<tr><td>Shift + Alt</td><td>Orange</td></tr>
	</tbody>
</table>

<p>
	<em>Claude:</em> the colours carry no meaning enforced by the app — an
	arrow is stored with its colour and drawn back exactly as you left it.
	They are yours to use consistently. The convention most chess sites and
	books share, and the one the underlying names suggest, is:
</p>

<ul>
	<li><strong>Green</strong> — the move to play, the good idea, the plan.</li>
	<li><strong>Red</strong> — the threat, the mistake, the square to avoid.</li>
	<li><strong>Blue</strong> — a note: an alternative line, a piece to notice, something to point at without judging it.</li>
	<li><strong>Orange</strong> — a warning short of a refutation: playable but careful, or the move that needs a condition met first.</li>
</ul>

<p>
	<em>Claude:</em> whatever you choose, keep it the same across a deck. A
	colour that means one thing on one card and something else on the next
	costs more attention than it saves.
</p>


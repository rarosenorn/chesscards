		<tr><td><kbd>Ctrl</kbd> + <kbd>B</kbd> / <kbd>I</kbd></td><td>Bold, italic</td></tr>
		<tr><td><kbd>Ctrl</kbd> + <kbd>U</kbd> / <kbd>O</kbd></td><td>Bullet list, numbered list</td></tr>
		<tr><td><kbd>Ctrl</kbd> + <kbd>K</kbd></td><td>Add a chessboard</td></tr>
		<tr><td><kbd>Shift</kbd> + <kbd>Enter</kbd></td><td>Line break within a paragraph</td></tr>
		<tr><td><kbd>Ctrl</kbd> + <kbd>Z</kbd> / <kbd>Y</kbd></td><td>Undo, redo</td></tr>

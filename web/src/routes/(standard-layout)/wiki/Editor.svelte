<p>
	Cards are written on the <strong>Add cards</strong> tab of a deck. A card
	has a front and a back; either side can hold text, chessboards, or both.
</p>

<h3>Text</h3>
<p>
	Both sides are rich text. The toolbar above the card carries the
	formatting, and each button names its shortcut:
</p>
<ul>
	<li><strong>Bold</strong> — ctrl-b</li>
	<li><em>Italic</em> — ctrl-i</li>
	<li>Bulleted list — ctrl-u</li>
	<li>Numbered list — ctrl-o</li>
	<li>Undo / redo — ctrl-z, ctrl-y</li>
</ul>

<h3>Chessboards</h3>
<p>
	<strong>Add chessboard</strong> (ctrl-k) drops a board into the side you
	are writing. A board is one block in the document: the text caret moves
	around it, and boards can be dragged within a block or between blocks.
	Each board carries a position, the moves played from it, and any
	annotations drawn on it.
</p>
<p>
	Two boards in one block render side by side on the finished card; a board
	on its own renders larger and centred. The editor shows the sizes the card
	will use, so what you write is what you study.
</p>

<h3>Card type</h3>
<p>
	<strong>Basic</strong> cards are scheduled by the spaced repetition
	algorithm — see <a href="?section=srs">SRS algorithm</a>.
	<strong>Tactic</strong> cards are graded correct or incorrect: correct
	finishes the card for good, incorrect brings it back the next day.
</p>
<p>
	The type applies to every card you add until you change it, as does the
	chapter the cards file into.
</p>

<h3>Chapters</h3>
<p>
	Every card belongs to a chapter, and every deck has at least one. Pick the
	chapter beside the card type; the <strong>+</strong> next to it starts a
	new one without leaving the tab. Chapters are reordered, renamed and
	deleted from the <strong>Cards</strong> tab.
</p>

<h3>Writing a run of cards</h3>
<p>
	<strong>Ctrl+Enter</strong> adds the card and clears the editor for the
	next one. The snowflake on a side <strong>freezes</strong> it (F9), so its
	content survives the submit — useful for a run of cards sharing one
	position or one stem. F9 with neither side focused freezes both.
</p>
<p>
	A half-written card is kept as you type, so switching tabs, leaving the
	deck or reloading does not lose it.
</p>

<h3>Editing later</h3>
<p>
	The <strong>Cards</strong> tab lists a deck's cards and edits any of them
	in place. In <strong>Study</strong>, the <em>Edit</em> button on the answer
	row (or the <em>e</em> key) opens the card you are looking at.
</p>

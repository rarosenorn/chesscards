<h3>Subdecks</h3>

<p>
	<em>Claude:</em> a deck starts out as one flat list. Turn <strong>Use
	subdecks</strong> on under the deck's <strong>Settings</strong> to group its
	cards, and the subdeck picker, the subdeck headers in Cards and the
	<code>2.17</code> card numbering appear. Switching it back off hides all of
	that again without touching the subdecks themselves, so turning it on later
	finds them as they were.
</p>

<h3>Subdeck progression</h3>

<p>
	With subdecks on, a deck can additionally hold its later subdecks shut until
	the earlier ones are learned, so a long deck introduces itself in order
	instead of all at once. Its own switch sits under the same
	<strong>Settings</strong>, below the one above.
</p>

<p>
	A subdeck <strong>passes</strong> when both are true of its cards:
</p>
<ul>
	<li>every card has been <strong>seen</strong> — met at least once</li>
	<li>at least <strong>80%</strong> have <strong>graduated</strong> — proved
		once, meaning they have reached Review. A card that lapses back to
		Relearning still counts: it was proved, and a lapse does not un-prove
		it. A tactic card graduates when you get it right and it finishes.</li>
</ul>

<p>
	Subdecks open <strong>cumulatively</strong>: the first is always open, and
	each next one opens once every subdeck before it has passed. So a subdeck
	is locked while any earlier one is still short of the bar, and study says
	which one is holding it and how far along that one is.
</p>

<p>
	Progression gates only the <strong>introduction of unseen cards</strong>.
	A card you have already met keeps coming back for review on schedule even
	if its subdeck has since fallen behind the bar — because cards were moved,
	or subdecks regrouped. Locking a subdeck never takes work away from you;
	it only stops new work arriving.
</p>

<p>
	Nothing is stored as an unlock flag. Whether a subdeck is open is worked
	out from the cards themselves each time, so resetting a deck's schedule
	re-locks its later subdecks by itself, and moving cards between subdecks
	takes effect immediately.
</p>

<p>
	An empty subdeck passes with nothing to prove, so it never holds up the
	ones after it.
</p>
